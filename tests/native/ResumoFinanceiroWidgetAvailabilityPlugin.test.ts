import fs from 'node:fs';
import path from 'node:path';

const { transformResumoFinanceiroWidgetAvailability } = jest.requireActual<{
  transformResumoFinanceiroWidgetAvailability: (source: string) => string;
}>('../../plugins/withResumoFinanceiroAvailability');

const repoRoot = path.resolve(__dirname, '../..');
const expoWidgetGeneratorSource = fs.readFileSync(
  path.join(repoRoot, 'node_modules/expo-widgets/plugin/src/ios/withWidgetSourceFiles.ts'),
  'utf8',
);

const generatedWidgetSource = [
  'import WidgetKit',
  'import SwiftUI',
  'import AppIntents',
  'internal import ExpoWidgets',
  '',
  'struct ResumoFinanceiroConfigurationAppIntent: WidgetConfigurationIntent {',
  '  @Parameter(title: "Modo", default: ResumoFinanceiroModeEnum.wholesale)',
  '  var mode: ResumoFinanceiroModeEnum',
  '}',
  'enum ResumoFinanceiroModeEnum: String, CaseIterable, AppEnum {',
  '  case wholesale',
  '  case retail',
  '}',
  'struct ResumoFinanceiroTimelineEntry: TimelineEntry {',
  '  let configuration: ResumoFinanceiroConfigurationAppIntent',
  '}',
  'struct ResumoFinanceiroTimelineProvider: AppIntentTimelineProvider {',
  '  func placeholder(in context: Context) -> ResumoFinanceiroTimelineEntry { fatalError() }',
  '}',
  'struct ResumoFinanceiroEntryView: View {',
  '  var body: some View { EmptyView() }',
  '}',
  '@available(iOS 17.0, *)',
  'struct ResumoFinanceiro: Widget {',
  '  var body: some WidgetConfiguration { EmptyWidgetConfiguration() }',
  '}',
].join('\n');

describe('ResumoFinanceiro iOS availability CNG plugin', () => {
  it('matches the App Intents declaration shapes generated by the installed Expo SDK', () => {
    for (const declaration of [
      'struct ${widget.name}ConfigurationAppIntent: WidgetConfigurationIntent {',
      'enum ${typeName}: String, CaseIterable, AppEnum {',
      'struct ${widget.name}TimelineEntry: TimelineEntry {',
      'struct ${widget.name}TimelineProvider: AppIntentTimelineProvider {',
      'struct ${widget.name}EntryView: View {',
    ]) {
      expect(expoWidgetGeneratorSource).toContain(declaration);
    }
  });

  it('annotates the generated iOS 17 App Intents types and leaves the iOS 17 widget declaration intact', () => {
    const transformed = transformResumoFinanceiroWidgetAvailability(generatedWidgetSource);

    for (const declaration of [
      'struct ResumoFinanceiroConfigurationAppIntent: WidgetConfigurationIntent {',
      'enum ResumoFinanceiroModeEnum: String, CaseIterable, AppEnum {',
      'struct ResumoFinanceiroTimelineEntry: TimelineEntry {',
      'struct ResumoFinanceiroTimelineProvider: AppIntentTimelineProvider {',
      'struct ResumoFinanceiroEntryView: View {',
    ]) {
      expect(transformed).toContain(`@available(iOS 17.0, *)\n${declaration}`);
    }
    expect(transformed).toContain('var mode: ResumoFinanceiroModeEnum');
    expect(transformed).toContain('@available(iOS 17.0, *)\nstruct ResumoFinanceiro: Widget {');
    expect(transformResumoFinanceiroWidgetAvailability(transformed)).toBe(transformed);
  });

  it('preserves CRLF and rejects missing or duplicated generated declarations', () => {
    const windowsSource = generatedWidgetSource.replace(/\n/g, '\r\n');
    const transformed = transformResumoFinanceiroWidgetAvailability(windowsSource);

    expect(transformed).toContain('\r\n@available(iOS 17.0, *)\r\n');
    expect(transformed.replace(/\r\n/g, '')).not.toContain('\n');
    expect(() =>
      transformResumoFinanceiroWidgetAvailability(
        generatedWidgetSource.replace(
          'struct ResumoFinanceiroTimelineProvider:',
          'struct ChangedProvider:',
        ),
      ),
    ).toThrow('expected exactly one declaration struct ResumoFinanceiroTimelineProvider:');
    expect(() =>
      transformResumoFinanceiroWidgetAvailability(
        generatedWidgetSource.replace(
          'struct ResumoFinanceiroTimelineProvider: AppIntentTimelineProvider {',
          'struct ResumoFinanceiroTimelineProvider: AppIntentTimelineProvider {\nstruct ResumoFinanceiroTimelineProvider: AppIntentTimelineProvider {',
        ),
      ),
    ).toThrow('expected exactly one declaration struct ResumoFinanceiroTimelineProvider:');
  });
});
